def call(
    operation: str, request: dict | None = None, *, root: Path | None = None
) -> dict[str, Any]:
    if operation not in CATALOG:
        return fail(
            "unknown",
            "unknown_operation",
            "operation is not in the workflow catalog",
            {"operation": operation},
        )
    workflow_root = Path(root) if root is not None else default_root()
    if operation not in READ_ONLY:
        workflow_root.mkdir(parents=True, exist_ok=True)
    try:
        result = HANDLERS[operation](dict(request or {}), workflow_root)
    except WorkflowError as exc:
        return from_error(operation, exc)
    except Exception as exc:  # noqa: BLE001 - unexpected failures stay structured
        return fail(operation, "internal", str(exc), {"error_type": type(exc).__name__})
    return ok(operation, result)
