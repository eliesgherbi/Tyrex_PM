def schema(dataset: str) -> pa.Schema:
    fields = DERIVED[dataset] if dataset in DERIVED else ENVELOPE + DATASETS[dataset]
    return pa.schema(fields, metadata={b"warehouse_schema": b"1", b"dataset": dataset.encode()})


def dictionary() -> dict:
    names = list(DATASETS) + list(DERIVED)
    return {name: {field.name: str(field.type) for field in schema(name)} for name in names}
